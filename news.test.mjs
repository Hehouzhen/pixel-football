import assert from 'node:assert/strict';
import {createSeason,completeWeek} from './league.mjs';
import {makeMatchNews,addMatchNews} from './news.mjs';
import {exportBackup,importBackup,makeClubSlot} from './save-slots.mjs';

const before=createSeason('england','arsenal',1),after=structuredClone(before);
completeWeek(after,[2,1]);
const base={before,after,mode:'club',score:[2,1],opponent:'Chelsea',stats:{shots:[7,4],onTarget:[3,2],saves:[1,1]}};
const article=makeMatchNews(base);
assert.match(article.headline,/击败|取胜/);
assert.match(article.lead,/2 : 1/);
assert.match(article.lead,/第 1 轮/);
assert.doesNotMatch(article.body,/从第/);
assert.deepEqual(article.stats.shots,[7,4]);
addMatchNews(after,article);
assert.equal(after.news[0].id,article.id);
const backup=importBackup(exportBackup({version:2,active:0,slots:[makeClubSlot(after),null,null]}));
assert.equal(backup.slots[0].season.news[0].headline,article.headline);
const career=makeMatchNews({...base,mode:'career',careerBefore:{stats:{goals:0}},careerAfter:{name:'新星',lastMatch:{goals:1,assists:0,rating:8.2}}});
assert.match(career.headline,/生涯首球/);
assert.match(career.body,/8\.2/);
const hatTrickNews=makeMatchNews({...base,mode:'career',careerBefore:{stats:{goals:8}},careerAfter:{name:'新星',lastMatch:{goals:3,assists:0,rating:9.4}}});
assert.match(hatTrickNews.headline,/帽子戏法/);
const fourGoalNews=makeMatchNews({...base,mode:'career',careerBefore:{stats:{goals:8}},careerAfter:{name:'新星',lastMatch:{goals:4,assists:0,rating:10}}});
assert.match(fourGoalNews.headline,/大四喜/);
assert.doesNotMatch(fourGoalNews.headline,/帽子戏法/);
const fiveGoalNews=makeMatchNews({...base,mode:'career',careerBefore:{stats:{goals:8}},careerAfter:{name:'新星',lastMatch:{goals:5,assists:0,rating:10}}});
assert.match(fiveGoalNews.headline,/五子登科/);
const sixGoalNews=makeMatchNews({...base,mode:'career',careerBefore:{stats:{goals:8}},careerAfter:{name:'新星',lastMatch:{goals:6,assists:0,rating:10}}});
assert.match(sixGoalNews.headline,/单场打入 6 球/);
assert.doesNotMatch(sixGoalNews.headline,/帽子戏法|五子登科/);
const variedHeadlines=new Set(['海港 FC','山城竞技','北岸联队','星河体育','蓝湾 FC','红叶俱乐部'].map(opponent=>makeMatchNews({...base,score:[1,1],opponent}).headline));
assert(variedHeadlines.size>1,'same-score news uses varied deterministic headlines');
const simulated=makeMatchNews({...base,source:'simulated',goalEvents:[{minute:12,teamId:'arsenal',scorerName:'前锋甲',assistName:'中场乙'},{minute:41,teamId:'arsenal',scorerName:'前锋甲'},{minute:66,teamId:'chelsea',scorerName:'前锋丙'}]});
assert.equal(simulated.source,'simulated');
assert.match(simulated.body,/12′ Arsenal：前锋甲（中场乙 助攻）/);
const cupBefore={...before,cup:{phase:'final'}},cupAfter={...after,cup:{phase:'complete',champion:'arsenal',results:[{}]}};
const cup=makeMatchNews({...base,before:cupBefore,after:cupAfter,competition:'cup'});
assert.match(cup.headline,/杯赛冠军/);
const penalty=makeMatchNews({...base,score:[1,1],shootout:{winner:'arsenal',score:[4,3]}});
assert.match(penalty.headline,/点球淘汰/);
console.log('PASS: match news facts, career milestone, simulation and cup results.');
